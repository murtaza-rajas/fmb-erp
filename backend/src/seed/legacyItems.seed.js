// source register — Item.model.js also requires categoryId, reorderLevel, and
// standardRate, none of which exist in the source, so:
//   - category: assigned by keyword judgment into the 5 categories the user asked
//     for (Grocery, Non Food Items, Vegetable, Cold Storage, Dairy Products) —
//     this is a best-effort classification, not from the source data.
//   - reorderLevel / standardRate: left as 0 placeholders (dev/test data only);
//     the register's "Min Level"/"Amount" columns were not reliably alignable
//     back to specific rows across the PDF's split-column pages, so rather than
//     risk silently-wrong numbers they were left as explicit 0 placeholders.
//   - sku: generated from the item name (see importLegacyData.js) since the
//     source has no SKU column.
//
